import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import pkg from "../package.json" with { type: "json" };

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const versionMatch = pkg.version.match(/^(\d+)\.(\d+)\.(\d+)(?:-([A-Za-z]+)(?:\.(\d+))?)?$/);

if (!versionMatch) {
  throw new Error(`package.json version must use SemVer: ${pkg.version}`);
}

const [, major, minor, patch, rawChannel, rawPrereleaseNumber] = versionMatch;
const marketingVersion = `${major}.${minor}.${patch}`;
const channel = rawChannel?.toLowerCase();
if (channel && !["alpha", "beta", "rc"].includes(channel)) {
  throw new Error(`Unsupported prerelease channel in package.json version: ${channel}`);
}

const prereleaseNumber = Math.min(Number(rawPrereleaseNumber ?? 0), 29);
const channelOffset = channel === "alpha" ? 1 : channel === "beta" ? 31 : channel === "rc" ? 61 : 99;
const buildNumber =
  Number(major) * 10_000_000 + Number(minor) * 100_000 + Number(patch) * 100 + channelOffset + prereleaseNumber;

if (buildNumber > 2_100_000_000) {
  throw new Error(`Computed mobile build number exceeds the platform limit: ${buildNumber}`);
}

const output = resolve(ROOT, "ios", "App", "App", "Version.xcconfig");
writeFileSync(
  output,
  [
    "// Generated by scripts/sync-ios-version.mjs. Do not edit.",
    `BIU_MARKETING_VERSION = ${marketingVersion}`,
    `BIU_CURRENT_PROJECT_VERSION = ${buildNumber}`,
    "",
  ].join("\n"),
);

console.log(`iOS version synced: ${pkg.version} -> ${marketingVersion} (${buildNumber})`);
